# // Tipo de operadores aritméticos en Python

a = 11
b = 5
print("Valores iniciales: a =", a, ", b =", b)

#Suma
suma = a + b
print("Suma:", suma)

#Resta  
resta = a - b
print("Resta:", resta)

#Multiplicación
multiplicacion = a * b
print("Multiplicación:", multiplicacion)

#División
division = a / b
print("División:", division)
#División entera
division_entera = a // b

#potenciación
potenciacion = a ** b
("Potenciación -> A**B = A elevado a B")
print("Potenciación:", potenciacion)

#Negación   
negacion = -a
print("a =", a)
print("Negación:", negacion)

#Módulo
modulo = a % b
print("Módulo o residuo de la divicionn de", a, "entre", b, ":", modulo)


#EJEMPLO DE USO DE OPERADORES ARITMÉTICOS
