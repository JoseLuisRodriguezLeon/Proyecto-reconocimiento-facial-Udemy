#// Operadores de incremento y decremento (o asignación) en Python

# Operador de asignación simple
a = 10
print("Valor inicial de a:", a)

# Incremento
print("--------------")
a += 5  # Equivalente a a = a + 5
print("Después de a += 5, a =", a)

print("--------------")

# Decremento
a -= 3  # Equivalente a a = a - 3
print("Después de a -= 3, a =", a)

print("--------------")

print("Esto es aplicable a otros operadores aritméticos también:")
a *= 2  # Equivalente a a = a * 2
print("Después de a *= 2, a =", a)
a /= 4  # Equivalente a a = a / 4
print("Después de a /= 4, a =", a)