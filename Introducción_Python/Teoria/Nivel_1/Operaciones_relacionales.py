# // Operaciones relacionales en Python

a = 10
b = 20
c = 10

print("Sabemos que a =", a, ", b =", b, ", c =", c)

# Igual que
print("Igual que:")
print("a == b:", a == b)
print("a == c:", a == c)

# Diferente o distinto que
print("Distinto que:")
print("a != b:", a != b)
print("a != c:", a != c)

# Mayor que
print("Mayor que:")
print("c > a:", c > a)
print("b > a:", b > a)

# Menor que
print("Menor que:")
print("c < a:", c < a)
print("a < b:", a < b)

# Mayor o igual que
print("Mayor o igual que:")
print("c >= a:", c >= a)
print("a >= c:", a >= c)

# Menor o igual que
print("Menor o igual que:")
print("c <= a:", c <= a)
print("a <= c:", a <= c)