# // Arrays en python
# Definición de un array (lista en Python)
array = [0,"Juan",4,True, "Maria", (1,2,3), 5.6]

print("Array completo:", array)

# Acceso a elementos individuales
print("Primer elemento:", array[0])        # Accede al primer elemento
print("Tercer elemento:", array[2])        # Accede al tercer elemento
print("Último elemento:", array[-1])       # Accede al último elemento

print("Elemento en la mitad del array:", array[len(array)//2])    # Accede al elemento en la mitad del array

print("Elementos desde el índice 1 hasta el 4:", array[1:5])  # Subarray desde el índice 1 hasta el 4


